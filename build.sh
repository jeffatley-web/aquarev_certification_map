<div id="arcm" data-theme="dark"></div>
<script defer src="https://cdnjs.cloudflare.com/ajax/libs/d3/3.5.17/d3.min.js"></script>
<script defer src="https://cdnjs.cloudflare.com/ajax/libs/topojson/1.6.9/topojson.min.js"></script>
<script defer src="https://cdnjs.cloudflare.com/ajax/libs/datamaps/0.5.9/datamaps.all.min.js"></script>
<script defer src="certification-map.js"></script>
</body>
</html>
EOF

# ================= Page 2: document =================
{
  echo "/* AquaRev Global Compliance Map (document). Generated by build.sh from the document master; do not edit by hand. */"
  awk '/^<style>$/{f=1;next} /^<\/style>$/{f=0} f' "$DOC" | scope_css arcd arcd-sticky-top
} > compliance-map.css

{
  echo "/* AquaRev Global Compliance Map (document). Generated by build.sh from the document master; do not edit by hand. */"
  echo "(function(){"
  echo "var root=document.getElementById('arcd'); if(!root) return;"
  echo "root.innerHTML=\`"
  awk '/^<div class="wrap">$/{f=1} f&&/^<script>$/{exit} f{print}' "$DOC" \
    | sed -E -e "s|$ARTIFACT_ATLAS|$SITE_MAP|g" -e 's/`/\\`/g'
  echo "\`;"
  nav_offset_js arcd-sticky-top
  awk '/^<script>$/{f=1;next} /^<\/script>$/{f=0} f' "$DOC"
  # Deep links from the atlas arrive as #anchors; scroll to them once the markup exists.
  echo "if(location.hash){ var t=document.getElementById(decodeURIComponent(location.hash.slice(1))); if(t){ setTimeout(function(){ t.scrollIntoView({block:'start'}); }, 80); } }"
  echo "window.addEventListener('hashchange',function(){ var t=document.getElementById(decodeURIComponent(location.hash.slice(1))); if(t) t.scrollIntoView({block:'start'}); });"
  echo "})();"
} > compliance-map.js

cat > webflow-embed-compliance-map.html <<EOF
<!-- AquaRev Global Compliance Map (document). Paste this whole block into a Webflow Embed element on /compliancemap.
     CSS and JS are hosted on GitHub Pages; bump the ?v= values after pushing changes. -->
<link rel="stylesheet" href="$FONTS">
<link rel="stylesheet" href="$PAGES/compliance-map.css?v=$STAMP">
<div id="arcd" data-theme="dark"></div>
<script defer src="$PAGES/compliance-map.js?v=$STAMP"></script>
EOF

cat > preview-doc.html <<EOF
